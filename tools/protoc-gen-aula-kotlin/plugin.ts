/**
 * protoc-gen-aula-kotlin
 *
 * pbandk generates the Kotlin MESSAGES but no services, and no Connect client supports Kotlin/Native.
 * This plugin writes, per proto service:
 *   - XxxServiceClient   typed suspend calls over RpcTransport (unary) / Flow (server streaming)
 *   - XxxQueries         one Query<T> factory per `NO_SIDE_EFFECTS` rpc (the React-Query "useQuery" side)
 *   - XxxMutations       one Mutation<I,O> per other rpc, with `invalidates` from the proto option
 * and one AulaApi that gathers them. The proto options are the only hand-authored metadata:
 *   (aula.options.v1.invalidates), (aula.options.v1.refetch_seconds).
 *
 * Rules enforced at generation time (it fails the build, on purpose):
 *   - a mutation with no `invalidates` prints a warning, so a forgotten invalidation shows up in CI;
 *   - an `invalidates` entry that is not an rpc name in the contract is an error.
 */
import { createEcmaScriptPlugin, runNodeJs } from "@bufbuild/protoplugin";
import { getOption } from "@bufbuild/protobuf";
import type { DescMethod, DescService } from "@bufbuild/protobuf";
import { invalidates, no_invalidation, refetch_seconds } from "./gen/aula/options/v1/options_pb.ts";

const ROOT = "org.aula.app.rpc";
// aula.courses.v1 -> org.aula.app.rpc.courses.v1 (must match kotlin_package_mapping in proto/buf.gen.yaml)
const kotlinPackage = (protoPackage: string) => `${ROOT}.${protoPackage.replace(/^aula\./, "")}`;
const lowerFirst = (s: string) => s.charAt(0).toLowerCase() + s.slice(1);
const isQuery = (m: DescMethod) => m.idempotency === 1; // NO_SIDE_EFFECTS

let lang: "kotlin" | "web" = "kotlin";

const plugin = createEcmaScriptPlugin({
  name: "protoc-gen-aula-kotlin",
  version: "v0.1.0",
  // `lang=web` emits the same hints as a TypeScript table for apps/web (see emitWeb below).
  parseOptions(options) {
    for (const { key, value } of options) {
      if (key === "lang") lang = value === "web" ? "web" : "kotlin";
      else if (key !== "target") throw new Error(`unknown option ${key}`);
    }
  },
  generateTs(schema) {
    const services: DescService[] = schema.files.flatMap((f) => f.services);
    const allMethodNames = new Set(services.flatMap((s) => s.methods.map((m) => m.name)));
    if (lang === "web") return emitWeb(schema, services, allMethodNames);
    const clients: { pkg: string; service: string }[] = [];

    for (const svc of services) {
      const pkg = kotlinPackage(svc.file.proto.package);
      const base = svc.name.replace(/Service$/, "");
      const path = pkg.replace(/\./g, "/");
      const f = schema.generateFile(`${path}/${svc.name}Client.kt`);
      clients.push({ pkg, service: svc.name });

      const lines: string[] = [];
      lines.push(`// GENERATED by tools/protoc-gen-aula-kotlin from ${svc.file.name}. Do not edit.`);
      lines.push(`package ${pkg}`, ``);
      lines.push(`import kotlinx.coroutines.flow.Flow`);
      lines.push(`import org.aula.app.query.Mutation`, `import org.aula.app.query.Query`, `import org.aula.app.query.QueryKey`);
      lines.push(`import org.aula.app.rpc.RpcTransport`, ``);

      lines.push(`class ${svc.name}Client(private val transport: RpcTransport) {`);
      for (const m of svc.methods) {
        const fn = lowerFirst(m.name);
        const path = `${svc.typeName}/${m.name}`;
        if (m.methodKind === "unary") {
          lines.push(`    suspend fun ${fn}(request: ${m.input.name} = ${m.input.name}()): ${m.output.name} =`);
          lines.push(`        transport.unary("${path}", request, ${m.output.name}.Companion)`);
        } else if (m.methodKind === "server_streaming") {
          lines.push(`    fun ${fn}(request: ${m.input.name}): Flow<${m.output.name}> =`);
          lines.push(`        transport.serverStream("${path}", request, ${m.output.name}.Companion)`);
        } else {
          throw new Error(`${path}: ${m.methodKind} is not supported by the Kotlin transport`);
        }
      }
      lines.push(`}`, ``);

      const queries = svc.methods.filter((m) => m.methodKind === "unary" && isQuery(m));
      lines.push(`/** One cached, watchable query per read rpc. Key = [rpc name, request]. */`);
      lines.push(`class ${base}Queries(private val api: ${svc.name}Client) {`);
      for (const m of queries) {
        const every = getOption(m, refetch_seconds);
        lines.push(`    fun ${lowerFirst(m.name)}(request: ${m.input.name} = ${m.input.name}()) = Query(`);
        lines.push(`        key = QueryKey("${m.name}", request.toString()),`);
        lines.push(`        fetch = { api.${lowerFirst(m.name)}(request) },`);
        if (every > 0) lines.push(`        refetchEveryMs = ${every * 1000}L,`);
        lines.push(`    )`);
      }
      lines.push(`}`, ``);

      const mutations = svc.methods.filter((m) => m.methodKind === "unary" && !isQuery(m));
      lines.push(`/** One mutation per write rpc; on success the generated client invalidates the queries named in the proto. */`);
      lines.push(`class ${base}Mutations(private val api: ${svc.name}Client) {`);
      for (const m of mutations) {
        const inv = getOption(m, invalidates);
        for (const name of inv) {
          if (!allMethodNames.has(name)) throw new Error(`${svc.name}.${m.name}: invalidates "${name}", which is not an rpc in the contract`);
        }
        if (inv.length === 0 && !getOption(m, no_invalidation)) console.error(`warning: ${svc.name}.${m.name} has no (aula.options.v1.invalidates): screens showing stale data will not refresh after it`);
        const keys = inv.map((n) => `QueryKey("${n}")`).join(", ");
        lines.push(`    val ${lowerFirst(m.name)} = Mutation<${m.input.name}, ${m.output.name}>(`);
        lines.push(`        run = { api.${lowerFirst(m.name)}(it) },`);
        if (inv.length) lines.push(`        invalidates = { _, _ -> listOf(${keys}) },`);
        lines.push(`    )`);
      }
      lines.push(`}`);
      f.print(lines.join("\n"));
    }

    // One object that wires everything. Screens/components ask for this, never for a raw transport.
    const f = schema.generateFile(`${ROOT.replace(/\./g, "/")}/AulaApi.kt`);
    const out: string[] = [`// GENERATED by tools/protoc-gen-aula-kotlin. Do not edit.`, `package ${ROOT}`, ``];
    for (const c of clients) {
      const base = c.service.replace(/Service$/, "");
      out.push(`import ${c.pkg}.${c.service}Client`, `import ${c.pkg}.${base}Queries`, `import ${c.pkg}.${base}Mutations`);
    }
    out.push(``, `class AulaApi(transport: RpcTransport) {`);
    for (const c of clients) {
      const base = c.service.replace(/Service$/, "");
      const n = lowerFirst(base);
      out.push(`    val ${n}Client = ${c.service}Client(transport)`);
      out.push(`    val ${n}Queries = ${base}Queries(${n}Client)`);
      out.push(`    val ${n}Mutations = ${base}Mutations(${n}Client)`);
    }
    out.push(`}`);
    f.print(out.join("\n"));
  },
});

/**
 * apps/web gets typed hooks from @connectrpc/connect-query (no codegen needed for the hooks themselves).
 * What connect-query does not know is OUR hints, so they are emitted as plain tables the web wrapper
 * (apps/web/src/rpc/hooks.ts) reads: which queries a mutation invalidates, and which queries poll.
 */
function emitWeb(schema: any, services: DescService[], allMethodNames: Set<string>) {
  const qualified = new Map<string, string>(); // rpc name -> "pkg.Service/Method"
  for (const svc of services) for (const m of svc.methods) qualified.set(m.name, `${svc.typeName}/${m.name}`);
  const inv: string[] = [], poll: string[] = [];
  for (const svc of services) {
    for (const m of svc.methods) {
      const list = getOption(m, invalidates);
      for (const n of list) if (!allMethodNames.has(n)) throw new Error(`${svc.name}.${m.name}: invalidates "${n}", which is not an rpc in the contract`);
      if (list.length) inv.push(`  "${svc.typeName}/${m.name}": [${list.map((n) => `"${qualified.get(n)}"`).join(", ")}],`);
      const every = getOption(m, refetch_seconds);
      if (every > 0) poll.push(`  "${svc.typeName}/${m.name}": ${every},`);
    }
  }
  const f = schema.generateFile("hints.ts");
  f.print(`// GENERATED by tools/protoc-gen-aula-kotlin (lang=web). Do not edit.`);
  f.print(`/** "pkg.Service/Method" of a mutation -> the "pkg.Service/Method" of every query it makes stale. */`);
  f.print(`export const invalidates: Record<string, string[]> = {\n${inv.join("\n")}\n};`);
  f.print(`/** Queries that poll while a screen watches them (seconds). Also the fallback when the stream is unavailable. */`);
  f.print(`export const refetchSeconds: Record<string, number> = {\n${poll.join("\n")}\n};`);
}

runNodeJs(plugin);
